package com.dtv.dcp.epoch.model.common.wireless;

/**
 * The Class FanDetails
 *
 */
public class FanDetails {

	private String fanAccountNumber;

	private String fanCompanyName;

	private String fanAgreementType;

	private String fanDiscountValue;

	private String fanDiscountUOM;

	public String getFanAccountNumber() {
		return fanAccountNumber;
	}

	public void setFanAccountNumber(String fanAccountNumber) {
		this.fanAccountNumber = fanAccountNumber;
	}

	public String getFanCompanyName() {
		return fanCompanyName;
	}

	public void setFanCompanyName(String fanCompanyName) {
		this.fanCompanyName = fanCompanyName;
	}

	public String getFanAgreementType() {
		return fanAgreementType;
	}

	public void setFanAgreementType(String fanAgreementType) {
		this.fanAgreementType = fanAgreementType;
	}

	public String getFanDiscountValue() {
		return fanDiscountValue;
	}

	public void setFanDiscountValue(String fanDiscountValue) {
		this.fanDiscountValue = fanDiscountValue;
	}

	public String getFanDiscountUOM() {
		return fanDiscountUOM;
	}

	public void setFanDiscountUOM(String fanDiscountUOM) {
		this.fanDiscountUOM = fanDiscountUOM;
	}

}
